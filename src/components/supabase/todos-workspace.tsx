'use client';

import {
  AlertCircle,
  Check,
  CheckCircle2,
  Copy,
  Database,
  Loader2,
  Plus,
  RefreshCw,
  Search,
  Trash2,
} from 'lucide-react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { useCallback, useEffect, useMemo, useState, type FormEvent } from 'react';

import { formatPlanCapacity } from '@/lib/plans';
import type { AuthUser, TodoItem, UserSubscription } from '@/types/supabase';

const TODOS_SQL_SNIPPET = `create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null default auth.uid(),
  title text not null check (char_length(title) > 0),
  is_complete boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.todos enable row level security;

create policy "Users can view their own todos"
  on public.todos for select
  using (auth.uid() = user_id);

create policy "Users can insert their own todos"
  on public.todos for insert
  with check (auth.uid() = user_id);

create policy "Users can update their own todos"
  on public.todos for update
  using (auth.uid() = user_id);

create policy "Users can delete their own todos"
  on public.todos for delete
  using (auth.uid() = user_id);`;

type FilterState = 'all' | 'pending' | 'completed';
type IntegrationIssue = 'none' | 'not_configured' | 'table_missing' | 'error';

export default function TodosWorkspace() {
  const router = useRouter();
  const [loading, setLoading] = useState(true);
  const [user, setUser] = useState<AuthUser | null>(null);
  const [subscription, setSubscription] = useState<UserSubscription | null>(
    null
  );
  const [configured, setConfigured] = useState<boolean>(false);
  const [issue, setIssue] = useState<IntegrationIssue>('none');
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const [todos, setTodos] = useState<TodoItem[]>([]);
  const [newTitle, setNewTitle] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [busyId, setBusyId] = useState<string | number | null>(null);

  const [filter, setFilter] = useState<FilterState>('all');
  const [searchQuery, setSearchQuery] = useState('');
  const [copiedSql, setCopiedSql] = useState(false);

  const loadWorkspace = useCallback(async () => {
    setLoading(true);
    setErrorMessage(null);

    try {
      const sessionRes = await fetch('/api/auth/session', {
        cache: 'no-store',
      });
      const sessionData = await sessionRes.json();

      setConfigured(Boolean(sessionData.configured));
      setUser(sessionData.user ?? null);

      if (!sessionData.configured) {
        setIssue('not_configured');
        setTodos([]);
        return;
      }

      if (!sessionData.authenticated) {
        router.replace('/login');
        return;
      }

      const [todosRes, planRes] = await Promise.all([
        fetch('/api/supabase/todos', { cache: 'no-store' }),
        fetch('/api/account/plan', { cache: 'no-store' }),
      ]);
      const todosData = await todosRes.json();
      if (planRes.ok) {
        const planData = await planRes.json();
        setSubscription(planData.subscription ?? null);
      }

      if (!todosRes.ok) {
        if (todosRes.status === 401) {
          router.replace('/login');
          return;
        }
        if (todosData.code === 'TABLE_NOT_FOUND') {
          setIssue('table_missing');
          setTodos([]);
          return;
        }
        setIssue('error');
        setErrorMessage(
          todosData.error ?? 'Erro ao carregar registros do Supabase.'
        );
        return;
      }

      setIssue('none');
      setTodos(Array.isArray(todosData.todos) ? todosData.todos : []);
    } catch {
      setIssue('error');
      setErrorMessage('Falha de conexão com o servidor.');
    } finally {
      setLoading(false);
    }
  }, [router]);

  useEffect(() => {
    void loadWorkspace();
  }, [loadWorkspace]);

  async function handleCreateTodo(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const title = newTitle.trim();
    if (!title || submitting) return;

    setSubmitting(true);
    setErrorMessage(null);

    try {
      const res = await fetch('/api/supabase/todos', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ title }),
      });
      const data = await res.json();

      if (!res.ok) {
        setErrorMessage(data.error ?? 'Não foi possível criar a tarefa.');
        return;
      }

      setTodos((prev) => [data.todo, ...prev]);
      setNewTitle('');
    } catch {
      setErrorMessage('Erro ao comunicar com o Supabase.');
    } finally {
      setSubmitting(false);
    }
  }

  async function handleToggleTodo(todo: TodoItem) {
    setBusyId(todo.id);
    setErrorMessage(null);

    try {
      const res = await fetch('/api/supabase/todos', {
        method: 'PATCH',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          id: todo.id,
          is_complete: !todo.is_complete,
        }),
      });
      const data = await res.json();

      if (!res.ok) {
        setErrorMessage(data.error ?? 'Não foi possível atualizar a tarefa.');
        return;
      }

      setTodos((prev) =>
        prev.map((item) => (item.id === todo.id ? data.todo : item))
      );
    } catch {
      setErrorMessage('Erro ao atualizar a tarefa.');
    } finally {
      setBusyId(null);
    }
  }

  async function handleDeleteTodo(id: string | number) {
    setBusyId(id);
    setErrorMessage(null);

    try {
      const res = await fetch(
        `/api/supabase/todos?id=${encodeURIComponent(String(id))}`,
        { method: 'DELETE' }
      );
      const data = await res.json();

      if (!res.ok) {
        setErrorMessage(data.error ?? 'Não foi possível excluir a tarefa.');
        return;
      }

      setTodos((prev) => prev.filter((item) => item.id !== id));
    } catch {
      setErrorMessage('Erro ao excluir a tarefa.');
    } finally {
      setBusyId(null);
    }
  }

  async function handleCopySql() {
    try {
      await navigator.clipboard.writeText(TODOS_SQL_SNIPPET);
      setCopiedSql(true);
      setTimeout(() => setCopiedSql(false), 2000);
    } catch {
      // Ignore clipboard failures in restricted environments
    }
  }

  const filteredTodos = useMemo(() => {
    const query = searchQuery.trim().toLowerCase();
    return todos.filter((todo) => {
      if (filter === 'pending' && todo.is_complete) return false;
      if (filter === 'completed' && !todo.is_complete) return false;
      if (query && !todo.title.toLowerCase().includes(query)) return false;
      return true;
    });
  }, [todos, filter, searchQuery]);

  const counts = useMemo(() => {
    const completed = todos.filter((t) => t.is_complete).length;
    return {
      total: todos.length,
      pending: todos.length - completed,
      completed,
    };
  }, [todos]);

  return (
    <div className="mx-auto max-w-5xl space-y-8">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <p className="text-sm font-medium text-emerald-700">
            Integração Vercel + Supabase
          </p>
          <h1 className="mt-1 text-2xl font-bold tracking-tight text-slate-900 sm:text-3xl">
            Painel da Clínica &amp; Tarefas
          </h1>
          <p className="mt-1.5 text-sm text-slate-600">
            {user
              ? `Conectado como ${user.email} · Tabela todos em tempo real via Supabase.`
              : 'Primeira integração configurada com @supabase/supabase-js.'}
          </p>
        </div>

        <button
          type="button"
          onClick={() => void loadWorkspace()}
          disabled={loading}
          className="inline-flex h-10 items-center justify-center gap-2 rounded-lg border border-slate-200 bg-white px-4 text-sm font-medium text-slate-700 transition-colors hover:bg-slate-50 disabled:opacity-60 whitespace-nowrap shrink-0"
        >
          <RefreshCw
            className={`h-4 w-4 ${loading ? 'animate-spin' : ''}`}
            aria-hidden="true"
          />
          Sincronizar
        </button>
      </div>

      {!loading && subscription && (
        <div className="flex flex-col gap-3 rounded-xl border border-slate-200 bg-white px-5 py-4 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-wrap items-center gap-2 text-sm">
            <span className="font-semibold text-slate-900">
              Plano {subscription.plan.name}
            </span>
            <span className="text-slate-300" aria-hidden="true">
              ·
            </span>
            <span className="text-slate-600 tabular-nums">
              {formatPlanCapacity(subscription.plan)}
            </span>
            {subscription.migration_pending && (
              <>
                <span className="text-slate-300" aria-hidden="true">
                  ·
                </span>
                <span className="text-xs font-medium text-amber-700">
                  Execute a migration de planos em sql.md
                </span>
              </>
            )}
          </div>
          <Link
            href="/configuracoes"
            className="text-sm font-medium text-emerald-700 transition-colors hover:text-emerald-800 whitespace-nowrap"
          >
            Gerenciar plano
          </Link>
        </div>
      )}

      {loading ? (
        <div className="rounded-xl border border-slate-200 bg-white p-6">
          <div className="space-y-3">
            <div className="h-5 w-48 animate-pulse rounded bg-slate-100" />
            <div className="h-11 w-full animate-pulse rounded-lg bg-slate-100" />
            <div className="h-11 w-full animate-pulse rounded-lg bg-slate-100" />
            <div className="h-11 w-full animate-pulse rounded-lg bg-slate-100" />
          </div>
        </div>
      ) : issue === 'not_configured' ? (
        <section className="rounded-xl border border-slate-200 bg-white p-6 sm:p-8">
          <div className="flex items-start gap-3">
            <Database
              className="mt-0.5 h-5 w-5 shrink-0 text-emerald-700"
              aria-hidden="true"
            />
            <div className="min-w-0 flex-1 space-y-4">
              <div>
                <h2 className="text-lg font-semibold text-slate-900">
                  Conecte seu projeto Supabase para ativar o banco de dados
                </h2>
                <p className="mt-1 text-sm leading-relaxed text-slate-600">
                  O cliente <code className="font-mono text-xs text-slate-800">@supabase/supabase-js</code> e as
                  rotas de autenticação e dados já estão prontos. Adicione as duas
                  variáveis de ambiente abaixo (no painel da Vercel ou nas
                  configurações de segredos):
                </p>
              </div>

              <div className="overflow-x-auto rounded-lg border border-slate-200 bg-slate-50 p-4 font-mono text-xs text-slate-800">
                <div>SUPABASE_URL=https://seu-projeto.supabase.co</div>
                <div>SUPABASE_ANON_KEY=sua-chave-anon-publica</div>
              </div>

              <div className="space-y-2 pt-2">
                <div className="flex items-center justify-between gap-4">
                  <h3 className="text-sm font-semibold text-slate-900">
                    SQL inicial da tabela <code className="font-mono text-xs">public.todos</code>
                  </h3>
                  <button
                    type="button"
                    onClick={() => void handleCopySql()}
                    className="inline-flex h-8 items-center gap-1.5 rounded-md border border-slate-200 bg-white px-3 text-xs font-medium text-slate-700 hover:bg-slate-50 whitespace-nowrap"
                  >
                    {copiedSql ? (
                      <>
                        <Check className="h-3.5 w-3.5 text-emerald-600" aria-hidden="true" />
                        Copiado
                      </>
                    ) : (
                      <>
                        <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                        Copiar SQL
                      </>
                    )}
                  </button>
                </div>
                <pre className="overflow-x-auto rounded-lg border border-slate-200 bg-slate-900 p-4 font-mono text-xs leading-relaxed text-slate-100">
                  {TODOS_SQL_SNIPPET}
                </pre>
              </div>

              <div className="flex flex-wrap items-center gap-3 pt-2">
                <Link
                  href="/login"
                  className="inline-flex h-10 items-center justify-center rounded-lg bg-emerald-600 px-4 text-sm font-semibold text-white transition-colors hover:bg-emerald-700 whitespace-nowrap"
                >
                  Ir para tela de login
                </Link>
                <button
                  type="button"
                  onClick={() => void loadWorkspace()}
                  className="inline-flex h-10 items-center justify-center rounded-lg border border-slate-200 bg-white px-4 text-sm font-medium text-slate-700 transition-colors hover:bg-slate-50 whitespace-nowrap"
                >
                  Verificar variáveis novamente
                </button>
              </div>
            </div>
          </div>
        </section>
      ) : issue === 'table_missing' ? (
        <section className="rounded-xl border border-amber-200 bg-white p-6 sm:p-8">
          <div className="space-y-4">
            <div className="flex items-start gap-3">
              <AlertCircle
                className="mt-0.5 h-5 w-5 shrink-0 text-amber-600"
                aria-hidden="true"
              />
              <div>
                <h2 className="text-lg font-semibold text-slate-900">
                  Supabase autenticado — crie a tabela <code className="font-mono text-base">todos</code>
                </h2>
                <p className="mt-1 text-sm text-slate-600">
                  Sua conexão e autenticação estão funcionando. Execute este SQL no
                  SQL Editor do Supabase para criar a tabela <code className="font-mono text-xs">public.todos</code> com políticas RLS por usuário:
                </p>
              </div>
            </div>

            <div className="flex justify-end">
              <button
                type="button"
                onClick={() => void handleCopySql()}
                className="inline-flex h-8 items-center gap-1.5 rounded-md border border-slate-200 bg-white px-3 text-xs font-medium text-slate-700 hover:bg-slate-50 whitespace-nowrap"
              >
                {copiedSql ? (
                  <>
                    <Check className="h-3.5 w-3.5 text-emerald-600" aria-hidden="true" />
                    Copiado
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                    Copiar SQL
                  </>
                )}
              </button>
            </div>

            <pre className="overflow-x-auto rounded-lg border border-slate-200 bg-slate-900 p-4 font-mono text-xs leading-relaxed text-slate-100">
              {TODOS_SQL_SNIPPET}
            </pre>

            <button
              type="button"
              onClick={() => void loadWorkspace()}
              className="inline-flex h-10 items-center justify-center gap-2 rounded-lg bg-emerald-600 px-4 text-sm font-semibold text-white transition-colors hover:bg-emerald-700 whitespace-nowrap"
            >
              <RefreshCw className="h-4 w-4" aria-hidden="true" />
              Testar consulta novamente
            </button>
          </div>
        </section>
      ) : (
        <section className="rounded-xl border border-slate-200 bg-white">
          <div className="border-b border-slate-200 p-6">
            <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
              <div>
                <h2 className="text-base font-semibold text-slate-900">
                  Lista de tarefas (<code className="font-mono text-xs text-slate-600">public.todos</code>)
                </h2>
                <div className="mt-1 flex items-center gap-2 text-xs text-slate-500 tabular-nums">
                  <span>{counts.total} no total</span>
                  <span aria-hidden="true">·</span>
                  <span>{counts.pending} pendentes</span>
                  <span aria-hidden="true">·</span>
                  <span>{counts.completed} concluídas</span>
                </div>
              </div>

              <div className="flex flex-wrap items-center gap-3">
                <div className="relative">
                  <Search
                    className="pointer-events-none absolute top-1/2 left-3 h-4 w-4 -translate-y-1/2 text-slate-400"
                    aria-hidden="true"
                  />
                  <input
                    type="search"
                    value={searchQuery}
                    onChange={(e) => setSearchQuery(e.target.value)}
                    placeholder="Buscar tarefa..."
                    aria-label="Buscar tarefa"
                    className="h-9 w-48 rounded-lg border border-slate-200 bg-white pr-3 pl-9 text-sm text-slate-900 placeholder:text-slate-400 focus:border-emerald-600 focus:ring-2 focus:ring-emerald-600/20 focus:outline-none"
                  />
                </div>

                <div
                  role="tablist"
                  aria-label="Filtrar tarefas"
                  className="flex items-center gap-1 rounded-lg bg-slate-100 p-1"
                >
                  {(
                    [
                      ['all', 'Todas'],
                      ['pending', 'Pendentes'],
                      ['completed', 'Concluídas'],
                    ] as const
                  ).map(([value, label]) => (
                    <button
                      key={value}
                      type="button"
                      role="tab"
                      aria-selected={filter === value}
                      onClick={() => setFilter(value)}
                      className={`h-7 rounded-md px-2.5 text-xs font-medium transition-colors whitespace-nowrap ${
                        filter === value
                          ? 'bg-white text-slate-900 shadow-xs'
                          : 'text-slate-600 hover:text-slate-900'
                      }`}
                    >
                      {label}
                    </button>
                  ))}
                </div>
              </div>
            </div>

            <form
              onSubmit={handleCreateTodo}
              className="mt-5 flex flex-col gap-3 sm:flex-row"
            >
              <input
                type="text"
                value={newTitle}
                onChange={(e) => setNewTitle(e.target.value)}
                placeholder="Ex.: Confirmar retorno do paciente João Silva"
                aria-label="Nova tarefa"
                maxLength={200}
                className="h-11 flex-1 rounded-lg border border-slate-300 bg-white px-3.5 text-sm text-slate-900 placeholder:text-slate-400 focus:border-emerald-600 focus:ring-2 focus:ring-emerald-600/20 focus:outline-none"
              />
              <button
                type="submit"
                disabled={submitting || !newTitle.trim()}
                className="inline-flex h-11 items-center justify-center gap-2 rounded-lg bg-emerald-600 px-5 text-sm font-semibold text-white transition-colors hover:bg-emerald-700 disabled:cursor-not-allowed disabled:opacity-60 whitespace-nowrap shrink-0"
              >
                {submitting ? (
                  <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
                ) : (
                  <Plus className="h-4 w-4" aria-hidden="true" />
                )}
                Adicionar tarefa
              </button>
            </form>

            {errorMessage && (
              <div
                role="alert"
                className="mt-4 flex items-center gap-2 rounded-lg border border-red-200 bg-red-50 px-3.5 py-2.5 text-sm text-red-800"
              >
                <AlertCircle className="h-4 w-4 shrink-0 text-red-600" aria-hidden="true" />
                <span>{errorMessage}</span>
              </div>
            )}
          </div>

          {filteredTodos.length === 0 ? (
            <div className="px-6 py-12 text-center">
              <CheckCircle2
                className="mx-auto h-8 w-8 text-slate-300"
                aria-hidden="true"
              />
              <p className="mt-3 text-sm font-medium text-slate-900">
                {todos.length === 0
                  ? 'Nenhuma tarefa cadastrada no Supabase ainda.'
                  : 'Nenhuma tarefa corresponde ao filtro atual.'}
              </p>
              <p className="mt-1 text-xs text-slate-500">
                {todos.length === 0
                  ? 'Use o campo acima para inserir o primeiro registro na tabela todos.'
                  : 'Limpe a busca ou troque o filtro para visualizar outros registros.'}
              </p>
            </div>
          ) : (
            <ul className="divide-y divide-slate-200">
              {filteredTodos.map((todo) => {
                const isBusy = busyId === todo.id;
                return (
                  <li
                    key={String(todo.id)}
                    className="flex items-center justify-between gap-4 px-6 py-3.5 transition-colors hover:bg-slate-50/70"
                  >
                    <div className="flex min-w-0 flex-1 items-center gap-3.5">
                      <button
                        type="button"
                        onClick={() => void handleToggleTodo(todo)}
                        disabled={isBusy}
                        aria-label={
                          todo.is_complete
                            ? `Marcar "${todo.title}" como pendente`
                            : `Marcar "${todo.title}" como concluída`
                        }
                        className={`flex h-5 w-5 shrink-0 items-center justify-center rounded border transition-colors ${
                          todo.is_complete
                            ? 'border-emerald-600 bg-emerald-600 text-white'
                            : 'border-slate-300 bg-white hover:border-emerald-600'
                        }`}
                      >
                        {todo.is_complete && (
                          <Check className="h-3.5 w-3.5" aria-hidden="true" />
                        )}
                      </button>

                      <div className="min-w-0 flex-1">
                        <p
                          className={`truncate text-sm font-medium ${
                            todo.is_complete
                              ? 'text-slate-400 line-through'
                              : 'text-slate-900'
                          }`}
                        >
                          {todo.title}
                        </p>
                      </div>
                    </div>

                    <div className="flex items-center gap-4 shrink-0">
                      {todo.created_at && (
                        <span className="hidden text-xs text-slate-400 tabular-nums sm:inline">
                          {new Date(todo.created_at).toLocaleDateString('pt-BR')}
                        </span>
                      )}
                      <button
                        type="button"
                        onClick={() => void handleDeleteTodo(todo.id)}
                        disabled={isBusy}
                        aria-label={`Excluir "${todo.title}"`}
                        className="inline-flex h-8 w-8 items-center justify-center rounded-md text-slate-400 transition-colors hover:bg-red-50 hover:text-red-600 disabled:opacity-50"
                      >
                        <Trash2 className="h-4 w-4" aria-hidden="true" />
                      </button>
                    </div>
                  </li>
                );
              })}
            </ul>
          )}
        </section>
      )}
    </div>
  );
}
